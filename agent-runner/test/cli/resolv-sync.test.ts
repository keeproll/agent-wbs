import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readlinkSync, realpathSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeEach, describe, expect, test } from 'vitest';

/**
 * DNS 사본 도우미(scripts/isolation/awbs-resolv-sync.sh, fix7)를 실제 bash로 돌린다. 실제 /etc는 건드리지 않는다.
 * - 원본·대상 경로와 「원본 소유자 UID」만 시험 폴더·시험 계정으로 바꾼 사본을 쓴다.
 */
const uid = process.getuid?.() ?? -1;
const usable = uid > 0;
const base = realpathSync(mkdtempSync(join(process.env.AWBS_TEST_TMP ?? tmpdir(), 'awbs-resolv-')));
afterAll(() => rmSync(base, { recursive: true, force: true }));
const original = readFileSync(join(import.meta.dirname, '..', '..', 'scripts', 'isolation', 'awbs-resolv-sync.sh'), 'utf8');
const MARK = '# Agent WBS(Q-08): /mnt/wsl/resolv.conf(WSL이 만든 원본)에서 awbs-resolv-sync가 옮긴 사본. 원본이 바뀌면 다시 옮긴다.';

let D = '';
let n = 0;
let src = '';
let dst = '';
let script = '';

function make(ownerUid = uid): void {
  D = join(base, `t${++n}`);
  mkdirSync(join(D, 'mnt/wsl'), { recursive: true });
  mkdirSync(join(D, 'etc'), { recursive: true });
  src = join(D, 'mnt/wsl/resolv.conf');
  dst = join(D, 'etc/resolv.conf');
  for (const line of ['\nSRC=/mnt/wsl/resolv.conf\n', '\nDST=/etc/resolv.conf\n', '\nSRC_OWNER_UID=0\n']) expect(original).toContain(line);
  script = join(D, 'sync.sh');
  writeFileSync(script, original
    .replace('\nSRC=/mnt/wsl/resolv.conf\n', `\nSRC=${src}\n`)
    .replace('\nDST=/etc/resolv.conf\n', `\nDST=${dst}\n`)
    .replace('\nSRC_OWNER_UID=0\n', `\nSRC_OWNER_UID=${ownerUid}\n`));
}
const sync = () => {
  const r = spawnSync('bash', [script], { encoding: 'utf8', env: { PATH: '/usr/bin:/bin' } });
  return { code: r.status, out: `${r.stdout}${r.stderr}` };
};
const WSL_SRC = '# This file was automatically generated by WSL.\n# [network]\nnameserver 10.255.255.254\nsearch kornet\n';

describe.skipIf(!usable)('awbs-resolv-sync: WSL DNS 설정을 /etc/resolv.conf 실제 파일로 옮김(fix7)', () => {
  beforeEach(() => make());

  test('WSL 링크 → 허용한 설정 줄만 담은 실제 파일(0644). 다시 실행하면 「이미 최신」', () => {
    writeFileSync(src, `${WSL_SRC}evil line\nnameserver\n`);
    symlinkSync(src, dst);
    let r = sync();
    expect(r.code, r.out).toBe(0);
    expect(lstatSync(dst).isSymbolicLink()).toBe(false);
    expect(readFileSync(dst, 'utf8')).toBe(`${MARK}\nnameserver 10.255.255.254\nsearch kornet\n`);
    expect(lstatSync(dst).mode & 0o777).toBe(0o644);
    r = sync();
    expect(r.out).toContain('이미 최신');
  });

  test('원본이 바뀌면 사본도 바꾸고, WSL이 다시 링크로 만들어도 다시 실제 파일로', () => {
    writeFileSync(src, WSL_SRC);
    symlinkSync(src, dst);
    sync();
    writeFileSync(src, 'nameserver 172.20.0.1\n');
    expect(sync().code).toBe(0);
    expect(readFileSync(dst, 'utf8')).toBe(`${MARK}\nnameserver 172.20.0.1\n`);
    rmSync(dst);
    symlinkSync(src, dst);
    expect(sync().code).toBe(0);
    expect(lstatSync(dst).isSymbolicLink()).toBe(false);
  });

  test('직접 관리하는 /etc/resolv.conf(표시 줄 없음)는 건드리지 않고 0', () => {
    writeFileSync(src, WSL_SRC);
    writeFileSync(dst, 'nameserver 1.1.1.1\n');
    const r = sync();
    expect(r.code).toBe(0);
    expect(r.out).toContain('직접 관리하는 파일');
    expect(readFileSync(dst, 'utf8')).toBe('nameserver 1.1.1.1\n');
  });

  test('다른 곳을 가리키는 링크(systemd-resolved 등)는 건드리지 않고 0', () => {
    writeFileSync(src, WSL_SRC);
    const other = join(D, 'stub-resolv.conf');
    writeFileSync(other, 'nameserver 127.0.0.53\n');
    symlinkSync(other, dst);
    expect(sync().code).toBe(0);
    expect(readlinkSync(dst)).toBe(other);
  });

  test('원본이 링크면(다른 계정이 심은 링크로 비밀 파일을 복사시키려는 경우) 실패하고 그대로 둔다', () => {
    const secret = join(D, 'shadow');
    writeFileSync(secret, 'nameserver 6.6.6.6\nroot:$6$secret\n');
    symlinkSync(secret, src);
    symlinkSync(src, dst);
    const r = sync();
    expect(r.code).toBe(1);
    expect(r.out).toContain('링크');
    expect(lstatSync(dst).isSymbolicLink()).toBe(true);
  });

  test('원본이 정한 소유자(root)가 아니면 실패하고 그대로 둔다', () => {
    make(0);
    writeFileSync(src, WSL_SRC);
    symlinkSync(src, dst);
    const r = sync();
    expect(r.code).toBe(1);
    expect(r.out).toContain('root 소유가 아닙니다');
    expect(lstatSync(dst).isSymbolicLink()).toBe(true);
  });

  test('nameserver 줄이 없으면 바꾸지 않는다(빈 DNS로 모두의 이름 찾기가 끊기지 않게)', () => {
    writeFileSync(src, '# only comments\nsearch kornet\n');
    symlinkSync(src, dst);
    const r = sync();
    expect(r.code).toBe(1);
    expect(lstatSync(dst).isSymbolicLink()).toBe(true);
    expect(spawnSync('ls', [join(D, 'etc')], { encoding: 'utf8' }).stdout.trim()).toBe('resolv.conf');
  });

  test('원본이 없으면 그대로 두고 0', () => {
    symlinkSync(src, dst);
    const r = sync();
    expect(r.code).toBe(0);
    expect(r.out).toContain('원본');
    expect(existsSync(src)).toBe(false);
  });

  test('원본을 읽지 못하면 실패(사본을 만들지 않음)', () => {
    writeFileSync(src, WSL_SRC);
    chmodSync(src, 0o000);
    symlinkSync(src, dst);
    try {
      expect(sync().code).not.toBe(0);
      expect(lstatSync(dst).isSymbolicLink()).toBe(true);
    } finally {
      chmodSync(src, 0o644);
    }
  });
});
